def get_profile(key: str) -> dict:
    return PROFILES.get(key, PROFILES["code"])


def list_profiles() -> list:
    return [(k, v["label"]) for k, v in PROFILES.items()]


def _ctx(bq: str, **kwargs) -> dict:
    """Готовит словарь подстановок: BQ + пользовательские."""
    return {"bq": bq, **kwargs}


def build_planner(profile_key: str, task: str, context: str = "") -> str:
    p = get_profile(profile_key)
    return PLANNER_PROMPT.format(
        hint=p["plan_hint"],
        task=task,
    ).replace("[CONTEXT]", context or "(нет контекста)")


def build_coder(profile_key: str, filename: str, task: str, action: str,
                project_files: str = "", context_block: str = "",
                requirements_block: str = "") -> str:
    p = get_profile(profile_key)
    return CODER_PROMPT.format(
        bq=BQ,
        hint=p["code_hint"],
        file=filename,
        task=task,
        action=action,
        project_files=project_files or "(нет других модулей)",
        context_block=context_block or "",
        requirements_block=requirements_block or "",
    )


def build_continue(filename: str, tail: str, action: str, task: str) -> str:
    return CONTINUE_PROMPT.format(
        bq=BQ, file=filename, tail=tail, action=action, task=task,
    )


def build_junior(profile_key: str, task: str, filename: str, code: str) -> str:
    p = get_profile(profile_key)
    return JUNIOR_PROMPT.format(
        bq=BQ, task=task, file=filename, code=code,
    )


def build_senior(profile_key: str, task: str, criteria: str,
                 filename: str, project_files: str, code: str) -> str:
    p = get_profile(profile_key)
    return SENIOR_PROMPT.format(
        bq=BQ, task=task, criteria=criteria or "(нет)",
        file=filename, project_files=project_files or "(нет)",
        code=code,
    )


def build_readme(task: str, files: str) -> str:
    return README_PROMPT.format(task=task, files=files)


